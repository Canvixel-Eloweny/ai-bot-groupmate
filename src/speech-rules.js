/**
 * ══════════════════════════════════════════════════════════════════════
 *  表达规范（ATI-1）—— 「像不像人」的可观测判据 + 写进提示词的那几行
 * ══════════════════════════════════════════════════════════════════════
 *  为什么单独一个模块，而不是把词表写在 brain.js 里：
 *    同一份清单有**两个消费者** ——
 *      ① 机器人把它写进提示词（教它别这么说）；
 *      ② 回复解析完之后扫一遍，把命中记进 trace（量"它到底说过几次"）。
 *    两处各写一份词表必然漂移，而漂移的表现是"提示词里禁了 X、统计里没有 X"，
 *    不报错、只是数字对不上 —— 本项目为这类事付过代价（三份拷贝的地址判据）。
 *
 *  ⚠️ **它不是闸门。命中只记录、不拦截。**
 *    出口闸门（凭据 / 本机路径）命中就整条不发，因为那件事的代价不可逆；
 *    而"说了句客服腔"的代价是"显得假" —— 为此拦掉一整条回复比它本身更糟，
 *    表现是"它突然不理我"，正是本项目最难查的那类失败。
 *    所以这里的顺序是：**先攒数字，再决定要不要收紧**。
 *
 *  ⚠️ **零依赖叶子**：不 import 任何模块（连 node: 内置都不引）。
 *    提示词侧（brain）与观测侧（index）都要引它，一旦它引了别的模块就可能成环。
 */

/**
 * 三组负向清单。`words` 里是**子串匹配**（不是分词）—— 中文短句里这样最省事也最可查。
 *
 * ⚠️ 已知的误报来源（刻意保留，因为本模块只观测不拦截）：
 *   · 「就这」「你必须」「确实」这类在日常聊天里也可能是正常说话；
 *     它们出现在清单里是为了**看频率**，不是判罪。
 *   · 词表**不做人称/场景区分**：同样一句"随便你"，在斗嘴和真撇清里不是一个意思。
 *     要区分得等有这个数字之后，按实际命中样本再谈。
 */
export const SPEECH_GROUPS = Object.freeze([
  Object.freeze({
    id: 'aiTone',
    label: 'AI 味 / 客服腔',
    why: '书面连接词、助手口吻、承诺式收尾 —— 一听就不是群里的人',
    words: Object.freeze([
      '首先', '其次', '综上所述', '总而言之', '值得注意的是', '值得一提的是',
      '作为 AI', '作为一个语言模型', '我是一个 AI',
      '希望这个回答对你有帮助', '有什么可以帮你', '有什么可以帮到你', '随时找我',
      '这是个好问题', '我理解你的感受', '让我来帮你', '祝你有美好的一天',
    ]),
  }),
  Object.freeze({
    id: 'sharp',
    label: '带刺 / 把人往外推',
    why: '冷嘲、反问呛人、命令式 —— 群里最伤气氛的一类',
    words: Object.freeze([
      '随便你', '你开心就好', '这你都不知道', '不然呢', '我不是说过了吗',
      '别废话', '你必须', '就这',
    ]),
  }),
  Object.freeze({
    id: 'echo',
    label: '空洞附和 / 无信息赞美',
    why: '"一个字的信息量，配不上一个包袱" —— 为填空而说的话',
    words: Object.freeze([
      '你说得对', '确实确实', '太棒了', '棒棒哒', '你真棒',
      '加油哦', '一定可以的', '相信你可以的',
    ]),
  }),
]);

/**
 * 合格 / 不合格的**边界对照**。这是"判断标准"能不能立住的关键 ——
 * 只说"别像客服"没人知道要什么，给一组"左边这样写就是假、右边才算说话"才落得了地。
 *
 * ⚠️ 这几组是**重写的**，不是从任何参考文档抄的文本；场景按本项目的实际对话形态挑的
 *    （被叫一声、道谢、发图、倒苦水、被问不会的）。
 */
const BOUNDARY_EXAMPLES = Object.freeze([
  Object.freeze({ scene: '被叫了一声、什么都没说', bad: '在的呀～有什么可以帮你的吗', good: '咋了' }),
  Object.freeze({ scene: '有人道谢', bad: '不客气，这是我应该做的', good: '嗯' }),
  Object.freeze({ scene: '有人发了张吃的东西', bad: '看起来很好吃，你很有品味', good: '哪买的' }),
  Object.freeze({ scene: '有人抱怨今天很累', bad: '我理解你的感受，要注意休息哦', good: '那早点睡' }),
  Object.freeze({ scene: '被问到不会的', bad: '这是个好问题，让我来帮你分析一下', good: '这我真不懂' }),
]);

/** 一个词在文本里出现的位置（供将来做"位置分布"用；当前只判有无） */
function hasWord(text, word) {
  return text.includes(word);
}

/**
 * 扫一遍文本，返回命中的组与词。**纯函数**：不碰 IO、不读时间、不调模型。
 *
 * @param {string} text 要检查的文本（多段就用空格拼起来传）
 * @returns {{hits:{group:string,word:string}[], groups:string[], count:number}}
 */
export function scanSpeech(text) {
  const s = String(text ?? '');
  if (!s) return { hits: [], groups: [], count: 0 };
  const hits = [];
  for (const g of SPEECH_GROUPS) {
    for (const w of g.words) {
      if (hasWord(s, w)) hits.push({ group: g.id, word: w });
    }
  }
  return { hits, groups: [...new Set(hits.map((h) => h.group))], count: hits.length };
}

/**
 * 写进提示词的那几行。**由本模块产出**，brain 只负责把它塞进哪一段
 * （段落在提示词里的位置属于拼装逻辑，属于 brain）。
 *
 * 为什么清单要写进提示词而不是"靠模型自觉"：
 *   模型对**具体词**的约束比对抽象要求（"自然一点"）服从得多；
 *   而"自然一点"这类词没法验收，具体词能。
 *
 * @returns {string[]}
 */
export function speechRuleLines() {
  const out = [];
  out.push('## 说话的红线（下面这些说了就是一秒露馅）');
  for (const g of SPEECH_GROUPS) out.push(`- ${g.label}：${g.words.join('、')}`);
  out.push('（宁可短、宁可只说半句，也不要用这些词把场面填满。）');
  out.push('');
  out.push('## 分寸对照（✗ 这样写是假；✓ 这样才算说话）');
  for (const b of BOUNDARY_EXAMPLES) out.push(`- ${b.scene}：✗ ${b.bad}；✓ ${b.good}`);
  return out;
}
