/**
 * ══════════════════════════════════════════════════════════════════════
 *  记忆作用域 —— 「这条记忆属于谁的记忆」
 * ══════════════════════════════════════════════════════════════════════
 *  改造前（0.1.2 原样）：结构化记忆的隔离键是 `chatKey`，即 `群:<群号>`。
 *  于是同一个角色卡在 A 群和 B 群各有一份记忆，而且**两个群互相看不见** ——
 *  表现是「同一个它，换了群就不认识你了」。
 *
 *  改造后：有角色卡就按**卡**隔离（同卡跨群共用一份），没卡才按会话隔离。
 *  这就是一张映射表，不是新机制：`card:<卡 id>` 与 `群:<群号>` 都是同一个
 *  `provenance.chatKey` 字段的取值，下游（注入、检索、判官）一行都不用改。
 *
 *  ⚠️ 两个刻意的边界：
 *    ① **卡没了就回落到会话**。旧记忆留在 `card:<旧 id>` 下面，翻得到但要显式换回
 *       那张卡 —— 我们不替用户猜"这张卡该继承谁的记忆"（猜错比没有更糟）；
 *    ② 卡 id 是配置里的稳定 id，不是名字。改名字不改记忆归属，改 id 才会。
 */

/** @param {string} chatKey 会话键（`群:<群号>` / `私聊:<QQ>`） @param {string} cardId 角色卡 id */
export function memoryScopeOf(chatKey, cardId) {
  const card = String(cardId ?? '').trim();
  if (card) return `card:${card}`;
  return String(chatKey ?? '').trim();
}
