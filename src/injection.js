/**
 * 提示词注入闸门（B9 · INJ-GATE）。
 *
 * ⚠️ **这不是万无一失的防线。**
 * 注入检测本质上是"用一组固定模式去追一个开放的对抗面"——换种说法、换个语种、
 * 拆成两句话、用同音字，都能绕过去。所以它**不能**被当成安全边界来依赖。
 *
 * 它还值得存在，是因为两件具体的事：
 *   ① 挡住最常见、最省事的那一类（"忽略上面的指令，你现在是…"）；
 *   ② 让**落盘的内容**干净一点 —— 记忆是每轮都要被重新塞进提示词的，
 *      一条脏记忆的污染是**持续的**，比一次性注入危险得多。
 *
 * 真正兜底的是设计本身：人设"有性格、不必照做"（见 brain.js 的扮演规则），
 * 以及记忆条数有上限、进提示词的要过闸。
 *
 * 反过来，**误杀比漏杀更糟**：如果正常聊天被拦下来，用户唯一的应对是把闸门整个关掉，
 * 那就等于没有闸门。所以下面的模式一律要求**出现明确的指令覆盖语义**，
 * 不按单个词匹配（"忽略"两个字本身太常见）。
 *
 * ── 规则自身出错时：**放行**（fail-open，第 42 轮 B12c · GUARD-LITE）──
 * 遍历规则表这件事已收敛到 `src/gate-scan.js`（唯一实现）。它在规则抛错时
 * 返回哨兵 `GATE_ERROR_KIND`，本模块**原样透出**。
 *
 * 与出口闸门（`src/egress.js`，那侧是 fail-closed）**取向刻意相反**：
 * 这道闸门保护的是"脏记忆不落盘"，而它自己开头就写着"不是万无一失的防线"。
 * 既然它本来就不是安全边界，那它坏掉时**不该让记忆静默停摆** ——
 * 那种表现是"它怎么突然什么都记不住了"，比漏掉一条脏记忆难查得多。
 *
 * ⚠️ 因此这个函数的返回值有**三种**：命中名 / `null` / 哨兵。
 *    两个调用点（`src/memory.js` · `panel/server.js`）必须用 `isBlocking()` 判，
 *    **不许**写成 `if (kind)` —— 那会把哨兵当成命中，等于安静地变成了 fail-closed。
 *    `check-wb.mjs` 第 12 节钉住这一条。
 */

import { scanRules, kindOf } from './gate-scan.js';

/** 命中就返回类别名，否则 null。纯函数，不读时钟、不碰 IO。 */
export const INJECTION_PATTERNS = [
  // ── 指令覆盖（中文）──
  // 必须同时出现"忽略/无视/忘记" + "上面/之前/所有" + "指令/规则/设定"三类词，
  // 缺一类都不算 —— 只为了一句"忽略上面那些人的话"就报警，那是误杀。
  {
    kind: '指令覆盖',
    re: /(忽略|无视|忘记|忘掉|抛弃|作废)[^。！？\n]{0,12}(上面|以上|之前|先前|前面|所有|全部)[^。！？\n]{0,8}(指令|规则|设定|设置|要求|提示词|prompt|身份|人格)/i,
  },
  {
    kind: '指令覆盖',
    re: /(上面|以上|之前|先前|前面)的?(所有|全部)?(指令|规则|设定|要求)[^。！？\n]{0,8}(全部)?(作废|无效|不算数|失效|清空)/,
  },
  // ── 指令覆盖（英文）──
  {
    kind: '指令覆盖',
    re: /\b(ignore|disregard|forget|override)\s+(all\s+|any\s+)?(previous|prior|above|earlier)\s+(instruction|instructions|prompt|prompts|rule|rules|message|messages)\b/i,
  },
  // ── 角色劫持 ──
  { kind: '角色劫持', re: /\byou\s+are\s+now\b/i },
  {
    kind: '角色劫持',
    re: /你现在(是|变成|扮演|充当)[^。！？\n]{0,10}(系统|管理员|开发者|助手|人工智能|语言模型|超级|最高)/,
  },
  {
    kind: '角色劫持',
    re: /(从现在起|从今天起|接下来|以后)[^。！？\n]{0,6}(你|你的)[^。！？\n]{0,6}(是|要当|要扮演|必须听|只能听)/,
  },
  // ── 套取系统提示词 ──
  { kind: '套取提示词', re: /\b(system|developer)\s+prompt\b/i },
  {
    kind: '套取提示词',
    re: /(把|输出|复述|重复|打印|告诉我)[^。！？\n]{0,10}(你的)?(系统)?(提示词|初始设定|system message)/i,
  },
  {
    kind: '套取提示词',
    re: /(以上|上面|之前)的?(全部)?(内容|文字|指令)[^。！？\n]{0,8}(原样)?(输出|打印|复述|发出来)/,
  },
  // ── 模板注入标记（聊天里正常不会出现这些）──
  { kind: '模板注入', re: /<\|(im_start|im_end|system|endoftext|assistant)\|>/i },
  {
    kind: '模板注入',
    re: /\[INST\]|\[\/INST\]|<<SYS>>|<\/SYS>|###\s*(System|Instruction|Assistant)\s*:/i,
  },
];

/**
 * 这段文本像不像一次注入尝试。
 *
 * @param {string} text
 * @returns {string|null}
 *   命中的类别名；未命中为 `null`；**规则自身抛错时为哨兵 `GATE_ERROR_KIND`**。
 *   （调用方一律用 `isBlocking()` 判断该不该拦 —— 见文件头的说明。）
 */
export function looksInjected(text) {
  // 规则一律**不带 g**：带 g 的正则 `.test()` 会留下 lastIndex，
  // 同一个正则连调两次会给出不同答案 —— 那是这类扫描器最经典的假阴性来源
  // （src/egress.js 的注释里有同一条教训）。遍历本身见 src/gate-scan.js。
  return kindOf(scanRules(INJECTION_PATTERNS, text));
}
