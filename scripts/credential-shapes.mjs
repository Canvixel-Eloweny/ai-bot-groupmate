/**
 * ══════════════════════════════════════════════════════════════════════
 *  凭据「形态」判据 —— **单一来源**（2026-10-04 审查轮 · n-6）
 * ══════════════════════════════════════════════════════════════════════
 *
 * 为什么抽出来：这两条判据原本只住在 `make-publish-copy.mjs` 里，
 * 于是**源头审计（`publish-audit.mjs`）看不到它们** ——
 * 结果是一种很别扭的形状：生成对外拷贝时会被拦下的东西，
 * 在"发布前体检"那一步**一路静默通过**（同一类判据只装在链路的一边）。
 *
 * ⚠️ 为什么必须只有一份：本项目的头号杀手是"同一份语义的第二份拷贝"。
 *    这条正则曾经就被抄过 —— 第一版写成 `/sk-[A-Za-z0-9]{16,}/` 而没有占位符排除，
 *    于是把 `test/smoke.js` 里两条**测试夹具**（字母表顺序的假 Key）判成了真 Key，
 *    产物以退出码 1 结束。两份拷贝只会让这类事故翻倍。
 *
 * 消费方（两处，都 import 这一份）：
 *   · `scripts/publish-audit.mjs`     —— 发布前审计**源头**
 *   · `scripts/make-publish-copy.mjs` —— 生成拷贝时的去标识 + **产物复扫**
 */

/**
 * ⚠️ 「疑似真 Key」必须先排除明显的占位符，否则它是个假阳性制造机。
 *
 * 判据：**含长串顺序字符**（字母表 / 数字表 / 键盘行）的一律视为占位符 ——
 * 真随机 Key 不可能长这样（这是"看起来像凭据"与"真的是凭据"的分界）。
 * ⚠️ 占位符仍然要**打印出来**（不静默），只是不计入失败 ——
 * 免得有人真把占位符换成了真 Key 却没人看见。
 */
export const PLACEHOLDER_RE = /(?:abcdefgh|12345678|01234567|stuvwxyz|qwerty|98765432)/i;

/**
 * 哨兵表（`known-real.mjs`）之外的补充形态：只查"像凭据"这一类。
 * 真值那部分**不走这里** —— 它由 `KNOWN_REAL` 负责（表驱动，可维护）。
 *
 * @type {Array<[RegExp, string]>}
 */
export const EXTRA_CREDENTIAL_SHAPES = [
  [/sk-[A-Za-z0-9]{16,}/g, '疑似真 Key'],
  // `Bearer <长串>`：日志与配置里最常见的另一种凭据形态。
  [/Bearer\s+[A-Za-z0-9._-]{20,}/g, '疑似 Bearer 令牌'],
  // PEM 私钥块的开头。私钥一旦入库，等同把身份交出去。
  [/-----BEGIN [A-Z ]*PRIVATE KEY-----/g, '私钥块'],
];
