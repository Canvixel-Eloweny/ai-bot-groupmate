/**
 * `href` 的**协议白名单**（2026-10-05 · 第 10 轮 · 开源前审查 H-01）
 * ══════════════════════════════════════════════════════════════════════════
 *  这个模块只回答一个问题：**"这个字符串能不能当链接的 href 用"**。
 *
 * ── 为什么需要它 ─────────────────────────────────────────────────────────
 *  `app.js` 的 `esc()` 只转义 `& < > " '` 五个字符 —— 它防的是**跳出属性**，
 *  不防**协议**。而 `javascript:alert(1)` 一个被转义的字符都不含，
 *  原样通过 `esc()` 之后仍然是一个可执行的 URI。
 *
 *  真正会撞上这条路径的是「AI免费额度情报」那一页：`it.url` 来自
 *  `data/api-deals.json`，而那个文件是**插件抓外部网站**写进去的
 *  （投影函数只做长度截断，`panel/lib/bot-data.js`）—— 属**二阶注入**：
 *  不信任的输入经由一个"数据文件"绕回了页面。
 *
 * ── 为什么单独一个文件、而不是写在 app.js 里 ─────────────────────────────
 *  `esc` 之类写在 app.js 里是**不可断言**的：那个文件一 import 就会建 DOM、
 *  发请求、起定时器，node 里根本跑不起来，于是"判据"只能退化成
 *  "在源码里 grep 一个正则" —— 而那种判据**测不出行为**（写对了没有、
 *  边界在哪儿，全靠读代码）。
 *
 *  抽成一个**零依赖叶子**之后，`test/smoke.js` 可以直接 `import` 它，
 *  用一组真值表把行为钉死（含 `javascript:` / 协议相对 / 大小写混合 / 前后空白
 *  这几个真实会出现的形态）。护栏因此是**行为**级，不是形状级。
 *
 * ⚠️ 本模块**不转义** —— 转义仍然由调用方 `esc()` 负责（两件事分开写，
 *    各自的判据才独立）。这里只保证"协议是 http/https 之一"。
 */

/** 放行的协议。⚠️ 只此一份，别处不许再写一遍这个正则。 */
export const SAFE_HREF_SCHEME = /^https?:\/\//i;

/**
 * 把一个候选值变成**可以安全放进 `href` 的原始 URL**。
 *
 * 规则极简：**只放行 `http://` / `https://` 开头，其他一律退化成 `#`**。
 * 这是"白名单"，不是"黑名单" —— 不试图列举 `javascript:` / `data:` / `vbscript:` /
 * `blob:` 这些已知坏协议，因为那份名单**永远列不完**，而漏掉的那一个就是下一个洞
 * （与项目在扩展包动作边界上立的那条同规：发言类用前缀判据，不用枚举）。
 *
 * 三个真实边界（都在 smoke 的真值表里）：
 *  · 前后空白先 trim —— `"\n javascript:…"` 曾让一批"以 javascript: 开头吗"的
 *    判据失效（浏览器解析 URL 时本来就会忽略前导空白，所以这里必须同口径）；
 *  · 大小写混合 —— `HtTpS://` 是合法 URL，不能因为它"看起来不像"就砍掉；
 *  · 协议相对（`//evil.example/x`）**不放行** —— 它继承页面的协议，
 *    看着无害，实际是一个可以指向任意外站的链接；面板里没有这种用法。
 *
 * @param {unknown} u
 * @returns {string} 原样返回（**未转义**）或 `'#'`
 */
export function safeHref(u) {
  const s = String(u === undefined || u === null ? '' : u).trim();
  return SAFE_HREF_SCHEME.test(s) ? s : '#';
}
